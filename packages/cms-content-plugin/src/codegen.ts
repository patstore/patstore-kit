import * as fs from 'node:fs';
import * as path from 'node:path';
import type { CmsContentMap } from './types.js';

export function writeContentArtifacts(outputDir: string, content: CmsContentMap): void {
	fs.mkdirSync(outputDir, { recursive: true });
	fs.writeFileSync(path.join(outputDir, 'cms-content.json'), JSON.stringify(content, null, 2), 'utf-8');
	fs.writeFileSync(path.join(outputDir, 'cms-content-data.ts'), generateContentData(), 'utf-8');
}

function generateContentData(): string {
	return `// Auto-generated by @patstore/cms-content-plugin — do not edit
import content from './cms-content.json';
import { bindCmsContent, type CmsContentFile } from '@patstore/cms-content-plugin/reader';

const api = bindCmsContent(content as CmsContentFile);

export function isCmsContentReady(): boolean {
	return api.isCmsContentReady();
}

export function getPageContent(pagePath: string, locale: string): Record<string, unknown> {
	return api.getPageContent(pagePath, locale);
}

export function getAllPageContent() {
	return api.getAllPageContent();
}
`;
}

export function writeStubContentArtifacts(outputDir: string): void {
	writeContentArtifacts(outputDir, {
		_meta: { generatedAt: '', projectId: '', source: 'defaults', languages: [] },
		pages: {},
	});
}
