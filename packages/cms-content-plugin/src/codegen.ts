import * as fs from 'node:fs';
import * as path from 'node:path';
import type { CmsContentMap } from './types.js';

export function writeContentArtifacts(outputDir: string, content: CmsContentMap): void {
	fs.mkdirSync(outputDir, { recursive: true });
	fs.writeFileSync(path.join(outputDir, 'cms-content.json'), JSON.stringify(content, null, 2), 'utf-8');
	fs.writeFileSync(path.join(outputDir, 'cms-content-data.ts'), generateContentData(), 'utf-8');
}

function generateContentData(): string {
	return `// Auto-generated by @patstore/cms-content-plugin — do not edit
import content from './cms-content.json';

export interface CmsContentPages {
	[path: string]: Record<string, unknown>;
}

interface CmsContentFile {
	_meta: { generatedAt: string; projectId: string; source: 'cms' | 'defaults'; languages: string[] };
	pages: CmsContentPages;
}

const data = content as CmsContentFile;

export function isCmsContentReady(): boolean {
	return Boolean(data._meta?.generatedAt);
}

/** \`de\` → \`de-DE\`. \`default\` stays \`default\`. */
function toLocale(value: string): string {
	const trimmed = value.trim();
	if (!trimmed || trimmed.toLowerCase() === 'default') {
		return 'default';
	}
	const parts = trimmed.split(/[-_]/).filter(Boolean);
	const language = parts[0]?.toLowerCase();
	if (!language) {
		return 'default';
	}
	const region = (parts[1] ?? parts[0]).toUpperCase();
	return \`\${language}-\${region}\`;
}

const LOCALE_PATH = /^[a-z]{2}-[A-Z]{2}\\./;

/**
 * Resolves \`pagePath\`'s \`page_data\` for \`locale\`. Paths are stored as they
 * come from the server (\`home_start.title\`, \`de-DE.home_start.title\`).
 * Unprefixed paths are the default; a locale prefix overrides that path.
 * With no languages or only one, only the unprefixed paths are returned.
 */
export function getPageContent(pagePath: string, locale: string): Record<string, unknown> {
	const page = data.pages[pagePath];
	if (!page) {
		return {};
	}
	const resolved: Record<string, unknown> = {};
	for (const [path, value] of Object.entries(page)) {
		if (!LOCALE_PATH.test(path)) {
			resolved[path] = value;
		}
	}
	const languages = data._meta?.languages ?? [];
	if (languages.length <= 1) {
		return resolved;
	}
	const prefix = \`\${toLocale(locale)}.\`;
	for (const [path, value] of Object.entries(page)) {
		if (path.startsWith(prefix)) {
			resolved[path.slice(prefix.length)] = value;
		}
	}
	return resolved;
}

export function getAllPageContent(): CmsContentPages {
	return data.pages;
}
`;
}

export function writeStubContentArtifacts(outputDir: string): void {
	writeContentArtifacts(outputDir, {
		_meta: { generatedAt: '', projectId: '', source: 'defaults', languages: [] },
		pages: {},
	});
}
